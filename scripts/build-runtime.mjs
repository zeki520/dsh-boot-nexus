/*
 * Concatenate the browser runtime into one self-contained IIFE.
 *
 * The runtime ships as ONE inline `kind:'script'` row. That is deliberate:
 * the desktop index interpreter executes script rows with createElement +
 * textContent, while `<script>` inside an `html` row is inserted with
 * insertAdjacentHTML and never runs. One inline script is also the only shape
 * that has no extra request to fail before the app's first paint.
 *
 * The sources are plain ES5-ish scripts with no imports. Keeping them as
 * separate files is for humans and tests; the browser only ever sees the
 * generated `lib/runtime.js`.
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import { fileURLToPath } from 'node:url'
import { dirname, join, resolve } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '..')
const runtimeDir = join(root, 'src', 'runtime')
const outDir = join(root, 'lib')
const outFile = join(outDir, 'runtime.js')

const FILES = [
  '00-constants.js',
  '10-fsm.js',
  '20-clock.js',
  '30-media.js',
  '35-scene.js',
  '37-suite.js',
  '40-stage.js',
  '50-boot.js',
]

const BUDGET = 64 * 1024
const HARD_LIMIT = 96 * 1024

const pkg = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'))
const parts = []
for (const name of FILES) {
  const source = await readFile(join(runtimeDir, name), 'utf8')
  if (/^\s*(import|export)\s/m.test(source)) {
    throw new Error(`${name}: runtime sources must not use ESM syntax`)
  }
  parts.push(`/* ---- ${name} ---- */\n${source.trim()}`)
}

const body = parts.join('\n\n')
const banner = `/* dsh-boot-nexus runtime v${pkg.version} — generated by scripts/build-runtime.mjs; do not edit. */`
const iife = `${banner}\n(function () {\n'use strict';\n${body}\n})();\n`
const bytes = Buffer.byteLength(iife)

if (bytes > HARD_LIMIT) {
  throw new Error(`runtime is ${bytes} bytes, over the ${HARD_LIMIT}-byte hard limit`)
}

await mkdir(outDir, { recursive: true })
await writeFile(outFile, iife, 'utf8')

const digest = createHash('sha256').update(iife).digest('hex')
await writeFile(
  join(outDir, 'runtime.meta.json'),
  `${JSON.stringify({ version: pkg.version, bytes, sha256: digest, files: FILES }, null, 2)}\n`,
  'utf8'
)

const status = bytes > BUDGET ? 'WARN over budget' : 'ok'
console.log(`runtime: ${bytes} bytes (${status}; budget ${BUDGET}, hard ${HARD_LIMIT})`)
console.log(`wrote ${outFile}`)
